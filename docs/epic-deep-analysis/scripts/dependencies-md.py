"""Render dependencies.md from data/dependencies.json and purposes.py. Usage: python3 dependencies-md.py <data-dir> <out.md>"""
import json, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from purposes import purpose
d = json.load(open(pathlib.Path(sys.argv[1]) / 'dependencies.json'))
ab = {'packages/workshop-app':'app','packages/workshop-utils':'utils','packages/workshop-cli':'cli','packages/workshop-mcp':'mcp','packages/workshop-presence':'presence','.':'root','other/update-workshops':'update-workshops'}
rows, missing = [], []
for n, v in d['dependencies'].items():
    decl = [x for x in v['declared'] if not x['package'].startswith('example')]
    files = [f for f in v['importingFiles'] if not f.startswith('example')]
    if not decl and not files: continue
    p = purpose(n)
    if not p: missing.append(n)
    where = ', '.join(sorted({ab.get(x['package'], x['package']) + ('' if x['kind'] == 'dependencies' else f" ({x['kind'].replace('Dependencies','')})") for x in decl})) or '(transitive)'
    ex = '; '.join(f'`{f}`' for f in files[:3]) + (f' +{len(files)-3}' if len(files) > 3 else '')
    rows.append(f"| `{n}` | {p} | {where} | {len(files)} | {ex or 'not imported: CLI, config, plugin or types'} |")
if missing: sys.exit(f'missing purposes: {missing}')
pathlib.Path(sys.argv[2]).write_text(f"""# Epic Workshop dependency inventory

Source: `epicweb-dev/epicshop` at `{d['commit']}`. Generated by `scripts/deps.py` and `scripts/dependencies-md.py` from every `package.json` (19 manifests) and every import in the source tree (example course excluded).

**{len(rows)} dependencies.** "Files" counts importing source files outside the example course. Packages: app = `packages/workshop-app`, utils = `packages/workshop-utils`, cli, mcp, presence, root, update-workshops.

| Package | What it is used for | Declared in | Files | Example usage sites |
|---|---|---|---|---|
""" + '\n'.join(rows) + "\n\nNode built-ins used: " + ', '.join(f"`{k}` ({v})" for k, v in d['nodeBuiltins'].items()) + "\n")
print(len(rows), 'dependencies')
